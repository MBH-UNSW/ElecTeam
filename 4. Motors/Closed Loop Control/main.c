static inline uint32_t ol_ccr(float d)
{
    if (d < 0.0f) d = 0.0f;
    if (d > 1.0f) d = 1.0f;
    return (uint32_t)(d * (float)s_period + 0.5f);
}

static inline void ol_write(float da, float db, float dc)
{
    __HAL_TIM_SET_COMPARE(&htim4, TIM_CHANNEL_2, ol_ccr(da));  /* IN1 / PB7 / A */
    __HAL_TIM_SET_COMPARE(&htim4, TIM_CHANNEL_1, ol_ccr(db));  /* IN2 / PB6 / B */
    __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_2, ol_ccr(dc));  /* IN3 / PB5 / C */
}

void ol_init(void)
{
    for (uint32_t i = 0; i < SIN_N; i++)
        s_sin[i] = sinf(TWO_PI_F * (float)i / (float)SIN_N);

    s_period = __HAL_TIM_GET_AUTORELOAD(&htim4) + 1u;

    ol_write(0.5f, 0.5f, 0.5f);          /* neutral: no phase-to-phase volts */
    HAL_TIM_PWM_Start(&htim4, TIM_CHANNEL_1);
    HAL_TIM_PWM_Start(&htim4, TIM_CHANNEL_2);
    HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_2);
    HAL_TIM_Base_Start_IT(&htim6);
}

/* Rotor electrical angle (0..255 = 0..360 elec deg) from the analog halls.
   Third hall reconstructed: for balanced 120-deg halls a+b+c = const.     */
static uint8_t hall_index(void)
{
    float a = (float)s_adc[0] - HALL_CENTER;
    float b = (float)s_adc[1] - HALL_CENTER;
    float c = -a - b;
    float alpha = a;
    float beta  = (b - c) * 0.57735027f;              /* 1/sqrt(3) */
    float th    = atan2f(beta, alpha);                /* -pi..pi   */
    return (uint8_t)(int32_t)(th * (256.0f / TWO_PI_F));
}

/* Drive a 3-phase sinusoid centred on 0.5 at electrical angle 'base'. */
static inline void drive_angle(uint8_t base, float m)
{
    ol_write(0.5f + 0.5f * m * s_sin[base],
             0.5f + 0.5f * m * s_sin[(uint8_t)(base + 85u)],
             0.5f + 0.5f * m * s_sin[(uint8_t)(base + 171u)]);
}

/* Align to field angle 0, learn the hall offset, then close the loop. */
void cl_start(float align_m, float run_m)
{
    s_closed = 0;                 /* hold electrical angle 0 */
    s_m      = align_m;
    s_run    = 1;
    HAL_Delay(700);               /* let the rotor settle */

    s_offset = hall_index();      /* hall reading at field angle 0 = zero ref */

    s_m      = run_m;
    s_closed = 1;                 /* self-commutating from here */
}

void cl_set_duty(float m)  { if (m < 0.0f) m = 0.0f; if (m > OL_M_MAX) m = OL_M_MAX; s_m = m; }
void cl_direction(int fwd) { s_dir = fwd ? 1 : -1; }

void cl_debug(uint16_t *h1, uint16_t *h2, uint8_t *ang, uint8_t *off)
{ if (h1)*h1=s_adc[0]; if (h2)*h2=s_adc[1]; if (ang)*ang=s_hall_idx; if (off)*off=s_offset; }

void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance != TIM6) return;

    if (s_run) {
        uint8_t field;
        if (s_closed) {
            uint8_t h = hall_index();
            s_hall_idx = h;
            /* field 90 elec-deg ahead of rotor, sign = direction */
            field = (uint8_t)(h - s_offset + (s_dir > 0 ? 64u : 192u));
        } else {
            field = 0;            /* align: hold electrical angle 0 */
        }
        drive_angle(field, s_m);
    }

    if (++s_hb >= (uint32_t)(OL_UPDATE_HZ / (2u * OL_STATUS_BLINK_HZ))) {
        s_hb = 0;
        HAL_GPIO_TogglePin(STATUS_LED_GPIO_Port, STATUS_LED_Pin);
    }
}
